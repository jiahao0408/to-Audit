import '../../data/export/export_keys.dart';
import '../../l10n/app_localizations.dart';

/// The labels the exporters ask for, translated to [l]'s language. [locale]
/// (`'es'` or `'zh'`) is carried along for money and date formatting.
/// Throws [ArgumentError] for a key with no translation.
ExportLabels exportLabels(AppLocalizations l, String locale) {
  String t(String key) => switch (key) {
    'sheetSummary' => l.export_sheetSummary,
    'sheetDays' => l.export_sheetDays,
    'sheetSales' => l.export_sheetSales,
    'sheetExpenses' => l.export_sheetExpenses,
    'sheetPayroll' => l.export_sheetPayroll,
    'sheetWithdrawals' => l.export_sheetWithdrawals,
    'colConcept' => l.export_colConcept,
    'colAmount' => l.export_colAmount,
    'colDate' => l.export_colDate,
    'colStatus' => l.export_colStatus,
    'colSales' => l.export_colSales,
    'colCovers' => l.export_colCovers,
    'colExpenses' => l.export_colExpenses,
    'colCashDiff' => l.export_colCashDiff,
    'colCardDiff' => l.export_colCardDiff,
    'colPaymentMethod' => l.export_colPaymentMethod,
    'colSupplier' => l.export_colSupplier,
    'colInvoice' => l.export_colInvoice,
    'colCategory' => l.export_colCategory,
    'colBase' => l.export_colBase,
    'colVatPct' => l.export_colVatPct,
    'colVat' => l.export_colVat,
    'colTotal' => l.export_colTotal,
    'colPayment' => l.export_colPayment,
    'colReceipts' => l.export_colReceipts,
    'colEmployee' => l.export_colEmployee,
    'colRole' => l.export_colRole,
    'colMonth' => l.export_colMonth,
    'colGross' => l.export_colGross,
    'colNet' => l.export_colNet,
    'colEmployerSs' => l.export_colEmployerSs,
    'colWithdrawalType' => l.export_colWithdrawalType,
    'reportTitle' => l.export_reportTitle,
    'restaurantNif' => l.export_restaurantNif,
    'period' => l.export_period,
    'generatedOn' => l.export_generatedOn,
    'totalSales' => l.export_totalSales,
    'totalPurchases' => l.export_totalPurchases,
    'totalFixedCosts' => l.export_totalFixedCosts,
    'totalOtherExpenses' => l.export_totalOtherExpenses,
    'totalExpenses' => l.export_totalExpenses,
    'totalPayroll' => l.export_totalPayroll,
    'totalWithdrawals' => l.export_totalWithdrawals,
    'totalCashDiscrepancy' => l.export_totalCashDiscrepancy,
    'totalCardDiscrepancy' => l.export_totalCardDiscrepancy,
    'pendingFixed' => l.export_pendingFixed,
    'vatPaid' => l.export_vatPaid,
    'averageTicket' => l.export_averageTicket,
    'profit' => l.export_profit,
    'dailyDetail' => l.export_dailyDetail,
    'statusOpen' => l.export_statusOpen,
    'statusClosed' => l.export_statusClosed,
    'statusNoActivity' => l.export_statusNoActivity,
    'paymentPaid' => l.export_paymentPaid,
    'paymentPending' => l.export_paymentPending,
    _ => throw ArgumentError.value(key, 'key', 'no export label'),
  };
  return ExportLabels(locale, t);
}
